/**
 * manager/web/managedBlock.ts — a section this plugin owns inside a file it
 * does not.
 *
 * Obsidian Publish loads exactly two files from a vault, `publish.js` and
 * `publish.css`, and a site that has them is very likely to have its own
 * things in them — a theme pasted into the stylesheet, a snippet of analytics
 * in the script. So the Publish export cannot own those files the way the
 * other targets own theirs. It owns a block:
 *
 *     /* callout-studio:start — …
 *      * fingerprint: <sha-256 of the body> *\/
 *     <body>
 *     /* callout-studio:end *\/
 *
 * Everything outside the two markers is the user's and is never read past
 * finding them. The fingerprint is the same idea as in `cssSnippetFile.ts`,
 * scoped to the block: it tells "the callouts changed" from "someone edited
 * our section", so the first is rewritten silently and the second asks.
 *
 * Both markers are comments in JavaScript and in CSS, so one format serves
 * both files.
 */
import { sha256 } from "../cssSnippetFile";

const START = "/* callout-studio:start";
const END = "/* callout-studio:end */";
const HEADER_END = " */\n";
const FINGERPRINT_RE = /\n \* fingerprint: ([0-9a-f]{64})$/;

/** What is between the markers in a file right now. */
export type BlockState =
	/** No block: the file has never held one, or does not exist. */
	| { kind: "none" }
	/** A block we wrote and nobody touched — `from`/`to` bound it in the file. */
	| { kind: "ours"; from: number; to: number; text: string }
	/** A block that was edited since, or whose header no longer reads. */
	| { kind: "edited"; from: number; to: number }
	/** A start marker with no end: there is no telling where it stops. */
	| { kind: "broken" };

/** The block for `body`: the markers, `prose` as its comment, the fingerprint. */
export async function buildBlock(prose: readonly string[], body: string): Promise<string> {
	const text = body.endsWith("\n") ? body : `${body}\n`;
	return (
		`${START} — generated by Callout Studio. Do not edit between this line and the end marker.\n` +
		prose.map((line) => (line ? ` * ${line}\n` : " *\n")).join("") +
		` * fingerprint: ${await sha256(text)}${HEADER_END}` +
		text +
		`${END}\n`
	);
}

/** Find the block in `file` and say whether it is still as we wrote it. */
export async function findBlock(file: string): Promise<BlockState> {
	const from = file.indexOf(START);
	if (from < 0) return { kind: "none" };
	const end = file.indexOf(END, from);
	if (end < 0) return { kind: "broken" };
	let to = end + END.length;
	if (file[to] === "\n") to++;

	const headerEnd = file.indexOf(HEADER_END, from);
	if (headerEnd < 0 || headerEnd > end) return { kind: "edited", from, to };
	const stamp = FINGERPRINT_RE.exec(file.slice(from, headerEnd));
	if (!stamp) return { kind: "edited", from, to };
	const body = file.slice(headerEnd + HEADER_END.length, end);
	return (await sha256(body)) === stamp[1]
		? { kind: "ours", from, to, text: file.slice(from, to) }
		: { kind: "edited", from, to };
}

/**
 * `file` with `block` in place: replacing the block that is there, or added at
 * the end, after a blank line, when there is none. `file` is `null` for a file
 * that does not exist yet.
 */
export function spliceBlock(file: string | null, state: BlockState, block: string): string {
	if (file === null || file.trim() === "") return block;
	if (state.kind === "ours" || state.kind === "edited")
		return file.slice(0, state.from) + block + file.slice(state.to);
	return `${file.replace(/\n*$/, "")}\n\n${block}`;
}
