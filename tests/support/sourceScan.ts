/** 1-based line number of `index` in `text`. */
export function lineOf(text: string, index: number): number {
	let line = 1;
	for (let i = 0; i < index && i < text.length; i++) {
		if (text[i] === "\n") line++;
	}
	return line;
}

/** `path:line`, the form the IDE turns into a link. */
export function at(file: SourceFile, index: number): string {
	return `${file.path}:${lineOf(file.text, index)}`;
}

/**
 * The span of a call's argument list, given the offset of its opening paren.
 *
 * Counts parens in the *blanked* text so a `(` inside a string does not throw
 * the balance off, and returns offsets into the original so the caller can slice
 * either view. Returns `null` for an unbalanced call, which cannot happen in
 * code that compiles but would otherwise be an infinite hunt.
 */
export function argSpan(
	code: string,
	openParen: number,
): { start: number; end: number } | null {
	let depth = 0;
	for (let i = openParen; i < code.length; i++) {
		const c = code[i];
		if (c === "(") depth++;
		else if (c === ")") {
			depth--;
			if (depth === 0) return { start: openParen + 1, end: i };
		}
	}
	return null;
}

/**
 * Every match of `re` in a file's *code* (literals blanked), as
 * `{ match, index }`. `re` must be global.
 */
export function codeMatches(
	file: SourceFile,
	re: RegExp,
): { match: RegExpMatchArray; index: number }[] {
	const out: { match: RegExpMatchArray; index: number }[] = [];
	for (const m of file.code.matchAll(re)) {
		out.push({ match: m, index: m.index ?? 0 });
	}
	return out;
}

/**
 * Formats a list of offending sites for an assertion message.
 *
 * Every check below reports *all* of its violations rather than the first: the
 * whole value of a ratchet is that you fix the batch once, and a message that
 * names one site at a time turns that into a dozen round trips.
 */
export function report(title: string, lines: string[]): string {
	return `${title}\n  ${lines.join("\n  ")}\n`;
}
